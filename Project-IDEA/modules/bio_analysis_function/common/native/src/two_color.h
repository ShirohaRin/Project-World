/*
 * two_color.h —— 二色合成化学测序仪的判定（上游 Evaluator::isTwoColorSystem）
 *
 * ============================================================================
 * 为什么需要它
 * ============================================================================
 *
 * Illumina 的双色合成化学里，G 被编码为"红绿两个荧光通道都没有信号"。
 * 信号变暗的一簇会被读成一串 G，于是在 read 尾部造出成片的假 polyG。
 * 上游据此**自动**为这类数据打开 polyG 修剪——用户不指定 `--trim_poly_g`
 * 也不指定 `--disable_trim_poly_g` 时，由数据自己决定。
 *
 * ============================================================================
 * 判据：只看第一条 read 的名字前缀
 * ============================================================================
 *
 * 不做任何统计，就是认仪器型号的名字前缀（见下）。这是上游的做法
 * （`OpenGene/fastp` PR #508 讨论后的结论），本实现照抄——判据虽简陋，
 * 但它有确定的答案，比"看尾部 G 的比例"更不容易误判。
 *
 * **注意前缀表的写法**：上游的 `Read::mName` **含行首的 '@'**，所以那边的表
 * 写的是 "@FS" 这一串；本模块的 `FastqRecord::name` 按约定**不含 '@'**
 * （见 fastq.h），因此这里的表去掉了 '@'。两边的语义完全一致。
 *
 * 它是个**工具**，不是算法：结论（是/否）自身对用户没有意义，必须被进一步
 * 处理（决定 polyG 修剪的开关）。按 `开发规则.md` 3.2 属于第 2 类，放在公共层。
 */

#ifndef BIO_TWO_COLOR_H
#define BIO_TWO_COLOR_H

#include <string>

namespace bio {

/*
 * 这份 FASTQ 是不是双色测序仪的产物。
 *
 * 只读**第一条记录**的名字。空文件返回 false。文件打不开会抛 InputFileError
 * （调用方本来就要能打开它才谈得上处理）。
 */
bool is_two_color_system(const std::string& read1_path);

}  // namespace bio

#endif /* BIO_TWO_COLOR_H */
